"""Structural typing for shared native presentation results; no native loading."""

from typing import Protocol


class _RuntimeStatus(Protocol):
    @property
    def name(self) -> str: ...
    @property
    def value(self) -> int: ...


class PresentationEnvironment(Protocol):
    @property
    def gpu_vendor(self) -> str: ...
    @property
    def gpu_renderer(self) -> str: ...
    @property
    def opengl_version(self) -> str: ...
    @property
    def refresh_rate_hz(self) -> int: ...
    @property
    def monitor_idx(self) -> int: ...
    @property
    def window_width(self) -> int: ...
    @property
    def window_height(self) -> int: ...
    @property
    def framebuffer_width(self) -> int: ...
    @property
    def framebuffer_height(self) -> int: ...
    @property
    def swap_interval(self) -> int: ...
    @property
    def fullscreen(self) -> bool: ...


class SoftwarePresentationTimes(Protocol):
    @property
    def status(self) -> _RuntimeStatus: ...
    @property
    def requested_ns(self) -> int: ...
    @property
    def intended_ns(self) -> int: ...
    @property
    def submitted_renderer_ns(self) -> int: ...
    @property
    def submitted_ns(self) -> int: ...
    @property
    def presented_renderer_ns(self) -> int: ...
    @property
    def presented_ns(self) -> int: ...
